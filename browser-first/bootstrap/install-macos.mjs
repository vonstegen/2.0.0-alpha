// CP-BR1: macOS installer for the ResonantOS bridge bootstrap native host.
//
// Installs, per-user:
//   1. a pinned wrapper script at
//        ~/Library/Application Support/ResonantOS/bootstrap/ros-bridge-bootstrap-host.sh
//      containing `exec "<pinned node>" "<pinned native-host-main.mjs>"`;
//   2. the Chrome native-host manifest at
//        ~/Library/Application Support/Google/Chrome/NativeMessagingHosts/com.resonantos.bridge_bootstrap.json
//      with `allowed_origins` pinned to the Alpha extension origin (no
//      wildcard, no caller-supplied origin).
//
// The Node executable is pinned by installation policy: by default it is
// the Node running this installer (`process.execPath`); `--node=` pins an
// alternate absolute path after an existence + version (>= 24) check. No
// ambient PATH lookup ever reaches the manifest.
//
// CLI:
//   node browser-first/bootstrap/install-macos.mjs [--node=/abs/node] [--print]
//
// `--print` performs a dry run: it prints the resolved paths, manifest, and
// wrapper without writing anything.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, realpathSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";
import {
  NATIVE_HOST_NAME,
  ROS_EXTENSION_ORIGIN,
  nativeHostEntryPath,
} from "./bridge-policy.mjs";

export const WRAPPER_FILE_NAME = "ros-bridge-bootstrap-host.sh";
export const MINIMUM_NODE_MAJOR = 24;

/**
 * Resolve every machine-local path the installer touches.
 *
 * @param {{ homeDir?: string }} [options]
 */
export function resolveInstallPaths({ homeDir = os.homedir() } = {}) {
  const supportDir = path.join(homeDir, "Library", "Application Support", "ResonantOS", "bootstrap");
  const manifestDir = path.join(homeDir, "Library", "Application Support", "Google", "Chrome", "NativeMessagingHosts");
  return {
    supportDir,
    wrapperPath: path.join(supportDir, WRAPPER_FILE_NAME),
    manifestDir,
    manifestPath: path.join(manifestDir, `${NATIVE_HOST_NAME}.json`),
  };
}

/**
 * Chrome native-host manifest. `allowed_origins` is pinned to the reviewed
 * extension origin by default; no wildcard is ever produced.
 *
 * @param {{ wrapperPath: string, extensionOrigins?: string[] }} options
 */
export function buildNativeHostManifest({ wrapperPath, extensionOrigins } = {}) {
  const origins = Array.isArray(extensionOrigins) && extensionOrigins.length > 0
    ? extensionOrigins
    : [ROS_EXTENSION_ORIGIN];
  for (const origin of origins) {
    if (typeof origin !== "string" || origin === "*" || !origin.startsWith("chrome-extension://")) {
      throw new Error("native-host manifest requires exact chrome-extension origins");
    }
  }
  return {
    name: NATIVE_HOST_NAME,
    description: "ResonantOS bridge bootstrap host (status/start/restart/stopForShutdown)",
    path: wrapperPath,
    type: "stdio",
    allowed_origins: origins,
  };
}

/**
 * Pinned wrapper script: exec the pinned Node with the pinned host entry.
 * No shell lookup, no ambient PATH influence on either operand.
 */
export function buildHostWrapperScript({ nodeExecutable, hostEntry } = {}) {
  for (const [label, value] of [["node executable", nodeExecutable], ["host entry", hostEntry]]) {
    if (typeof value !== "string" || !path.isAbsolute(value)) {
      throw new Error(`${label} must be an absolute path`);
    }
    if (value.includes('"') || value.includes("\n")) {
      throw new Error(`${label} must not contain quotes or newlines`);
    }
  }
  return [
    "#!/bin/sh",
    "# ResonantOS bridge bootstrap native host wrapper.",
    "# Generated by browser-first/bootstrap/install-macos.mjs; regenerate by re-running the installer.",
    `exec "${nodeExecutable}" "${hostEntry}"`,
    "",
  ].join("\n");
}

/**
 * Validate a candidate pinned Node executable: absolute, exists, and new
 * enough. Returns a public-safe verdict (never echoes the path in tokens).
 *
 * @param {string} nodeExecutable
 * @param {{ existsSyncImpl?: typeof existsSync, execFileSyncImpl?: typeof execFileSync }} [seams]
 */
export function validateNodeExecutable(nodeExecutable, {
  existsSyncImpl = existsSync,
  execFileSyncImpl = execFileSync,
} = {}) {
  if (typeof nodeExecutable !== "string" || !path.isAbsolute(nodeExecutable)) {
    return { ok: false, reason: "node-not-absolute" };
  }
  if (!existsSyncImpl(nodeExecutable)) {
    return { ok: false, reason: "node-missing" };
  }
  let versionText;
  try {
    versionText = String(execFileSyncImpl(nodeExecutable, ["--version"], { encoding: "utf8" })).trim();
  } catch {
    return { ok: false, reason: "node-not-runnable" };
  }
  const major = Number(/^v?(\d+)/.exec(versionText)?.[1]);
  if (!Number.isInteger(major) || major < MINIMUM_NODE_MAJOR) {
    return { ok: false, reason: "node-too-old" };
  }
  return { ok: true, version: versionText };
}

/**
 * Install (or, with dryRun, describe) the native host.
 *
 * @param {{
 *   nodeExecutable?: string,
 *   hostEntry?: string,
 *   homeDir?: string,
 *   dryRun?: boolean,
 *   extensionOrigins?: string[],
 *   existsSyncImpl?: typeof existsSync,
 *   mkdirSyncImpl?: typeof mkdirSync,
 *   writeFileSyncImpl?: typeof writeFileSync,
 *   execFileSyncImpl?: typeof execFileSync,
 * }} [options]
 * @returns {{ ok: boolean, reason?: string, paths?: object, manifest?: object, wrapper?: string }}
 */
export function installBootstrapNativeHost({
  nodeExecutable = process.execPath,
  hostEntry = nativeHostEntryPath(),
  homeDir,
  dryRun = false,
  extensionOrigins,
  existsSyncImpl = existsSync,
  mkdirSyncImpl = mkdirSync,
  writeFileSyncImpl = writeFileSync,
  execFileSyncImpl = execFileSync,
} = {}) {
  const nodeVerdict = validateNodeExecutable(nodeExecutable, { existsSyncImpl, execFileSyncImpl });
  if (!nodeVerdict.ok) return { ok: false, reason: nodeVerdict.reason };
  if (!existsSyncImpl(hostEntry)) return { ok: false, reason: "host-entry-missing" };

  const paths = resolveInstallPaths({ homeDir: homeDir ?? os.homedir() });
  const manifest = buildNativeHostManifest({ wrapperPath: paths.wrapperPath, extensionOrigins });
  const wrapper = buildHostWrapperScript({ nodeExecutable, hostEntry });

  if (!dryRun) {
    mkdirSyncImpl(paths.supportDir, { recursive: true });
    mkdirSyncImpl(paths.manifestDir, { recursive: true });
    writeFileSyncImpl(paths.wrapperPath, wrapper, { mode: 0o755 });
    writeFileSyncImpl(paths.manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, { mode: 0o644 });
  }
  return { ok: true, paths, manifest, wrapper, nodeVersion: nodeVerdict.version };
}

function parseInstallerArgs(argv) {
  const parsed = { node: undefined, print: false };
  for (const arg of argv) {
    if (arg === "--print") parsed.print = true;
    else if (arg.startsWith("--node=")) parsed.node = arg.slice("--node=".length);
    else return null;
  }
  return parsed;
}

const isMain = (() => {
  const entry = process.argv[1];
  if (typeof entry !== "string" || entry.length === 0) return false;
  try {
    return import.meta.url === pathToFileURL(realpathSync(entry)).href;
  } catch {
    return import.meta.url === pathToFileURL(entry).href;
  }
})();

if (isMain) {
  const args = parseInstallerArgs(process.argv.slice(2));
  if (!args) {
    console.error("usage: node browser-first/bootstrap/install-macos.mjs [--node=/abs/node] [--print]");
    process.exit(64);
  }
  const result = installBootstrapNativeHost({
    nodeExecutable: args.node ?? process.execPath,
    dryRun: args.print,
  });
  if (!result.ok) {
    console.error(`install failed: ${result.reason}`);
    process.exit(1);
  }
  const mode = args.print ? "dry run (no files written)" : "installed";
  console.log(JSON.stringify({
    mode,
    nodeVersion: result.nodeVersion,
    wrapperPath: result.paths.wrapperPath,
    manifestPath: result.paths.manifestPath,
    manifest: result.manifest,
  }, null, 2));
  if (!args.print) {
    console.log("Reload the extension or restart Chrome so the native host manifest is picked up.");
  }
}
